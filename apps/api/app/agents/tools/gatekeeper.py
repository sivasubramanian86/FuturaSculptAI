class AuditSaifControlsInput(BaseModel):
    """Input contract for audit_saif_controls tool."""

    scenario_prompt: str = Field(..., min_length=1, description="Scenario prompt to audit.")
    autonomy_tier: str = Field(..., description="Autonomy risk tier (A0_READ_ONLY to A4_DISALLOWED).")

    @field_validator("autonomy_tier")
    @classmethod
    def validate_tier_format(cls, v: str) -> str:
        """Enforce standard A0-A4 autonomy tier string format."""
